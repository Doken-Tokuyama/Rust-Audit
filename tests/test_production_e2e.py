def test_config_disables_exactly_the_named_rule(prod_workspace, project, tmp_path):
    golden = PROJECTS[project]
    cfg = tmp_path / "rust-audit.toml"
    cfg.write_text('[rules]\ndisabled = ["R02"]\n')
    scan(prod_workspace, tmp_path / "cfg", "--config", str(cfg),
         "--fail-on", "high")
