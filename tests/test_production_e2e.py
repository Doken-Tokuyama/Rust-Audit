def test_fix_is_transactional_and_idempotent_on_production_code(workspaces, tmp_path):
    # Documented safe-fix policy: fmt + clippy --fix (MachineApplicable) MAY
    # rewrite sources; the contract is that fix deletes nothing, adds only the
    # generated policy file, passes validation without rollback and converges.
    #
    # Proven end-to-end on ripgrep only: the cargo validation `fix` must pass
    # before committing costs ~10 min on tokio (measured 9m56s), so the double
    # run needed for idempotency would dominate the suite. `fix --dry-run`
    # (above) runs on every pinned workspace.
    ws = tmp_path / "applied"
    shutil.copytree(workspaces["ripgrep"], ws,
                    ignore=shutil.ignore_patterns(".git", "target", "report"))
    before = snapshot(ws)
    p1 = run("fix", str(ws), timeout=1800)
    assert p1.returncode == 0, p1.stdout + p1.stderr
    assert "REVERTED" not in p1.stdout, "validation failed and fix rolled back"
    after = snapshot(ws)
    missing = set(before) - set(after)
    added = set(after) - set(before)
    assert not missing, f"fix deleted production files: {sorted(missing)}"
    assert added <= GENERATED, f"unexpected new files: {sorted(added - GENERATED)}"

    # Transactional contract: a second run must apply nothing (idempotent).
    p2 = run("fix", str(ws), timeout=1800)
    assert p2.returncode == 0, p2.stdout + p2.stderr
    assert snapshot(ws) == after, "second fix run must apply nothing"
