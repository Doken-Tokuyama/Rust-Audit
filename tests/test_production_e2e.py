"""Production E2E suite for Rust Audit: real CLI against a real Rust workspace.

No synthetic demo fixture: the suite fetches BurntSushi/ripgrep at a pinned
commit and audits that production code end-to-end through the public CLI
(scan / fix / selftest). The golden numbers below are deterministic because
the workspace is pinned by commit; update them deliberately when the tool's
heuristics change on purpose.

Needs network to fetch the pinned workspace and Python 3.11+ (the tool uses
``tomllib``):

    python3 -m venv .venv && .venv/bin/pip install pytest
    .venv/bin/python -m pytest tests/
"""
from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
TOOL = ROOT / "scripts" / "rust_audit.py"

# Production workspace audited end-to-end, pinned by commit for determinism.
PROD_URL = "https://github.com/BurntSushi/ripgrep"
PROD_SHA = "3fce3b5bb0236da2df6d99672afb8a719642eca7"

# Golden results of `scan` on PROD_URL @ PROD_SHA (captured 2026-10-16).
GOLDEN_TOTAL = 1493
GOLDEN_BY_SEVERITY = {"critical": 2, "high": 874, "medium": 19, "low": 582, "info": 16}
GOLDEN_BY_RULE = {
    "R02": 835, "R03": 464, "R09": 141, "R04": 22, "R14": 12, "R10": 6,
    "R20": 3, "R11": 2, "R18c": 2, "R08": 1, "R12": 1, "R18a": 1,
    "R18d": 1, "R18e": 1, "R21": 1,
}

# Directories regenerated by tool/cargo runs: excluded from change detection.
NOISE_DIRS = {".git", "target", "report"}
GENERATED = {"deny.toml"}  # fix is allowed to create the dependency policy file


def run(*args: str, timeout: int = 600) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(TOOL), *args],
                          capture_output=True, text=True, timeout=timeout)


def scan(target: Path, out: Path, *extra: str) -> subprocess.CompletedProcess:
    return run("scan", str(target), "--format", "terminal,md,json,sarif",
               "--out", str(out), *extra)


def report(out: Path) -> dict:
    files = sorted(out.glob("rust-audit-*.json"))
    assert files, f"no JSON report written to {out}"
    return json.loads(files[0].read_text())


def snapshot(root: Path) -> dict[str, str]:
    """sha256 of every meaningful file; used to prove non-destruction."""
    out = {}
    for p in sorted(root.rglob("*")):
        if not p.is_file():
            continue
        rel = p.relative_to(root)
        if rel.parts[0] in NOISE_DIRS:
            continue
        out[rel.as_posix()] = hashlib.sha256(p.read_bytes()).hexdigest()
    return out


@pytest.fixture(scope="session")
def prod_workspace(tmp_path_factory) -> Path:
    ws = tmp_path_factory.mktemp("production-e2e") / "workspace"
    ws.mkdir()
    steps = [
        ["git", "init", "-q", str(ws)],
        ["git", "-C", str(ws), "remote", "add", "origin", PROD_URL],
        ["git", "-C", str(ws), "fetch", "-q", "--depth", "1", "origin", PROD_SHA],
        ["git", "-C", str(ws), "checkout", "-q", "FETCH_HEAD"],
    ]
    try:
        for argv in steps:
            subprocess.run(argv, check=True, capture_output=True, timeout=300)
    except (subprocess.CalledProcessError, subprocess.TimeoutExpired) as exc:
        pytest.fail(f"production E2E needs network to fetch {PROD_URL}@"
                    f"{PROD_SHA[:12]}: {exc}")
    return ws


def test_selftest_passes():
    p = run("selftest")
    assert p.returncode == 0, p.stdout + p.stderr
    assert "selftest PASS" in p.stdout


def test_scan_matches_golden_on_production_code(prod_workspace, tmp_path):
    p = scan(prod_workspace, tmp_path, "--fail-on", "high")
    assert p.returncode == 1, "real findings at/above --fail-on high must exit 1"
    data = report(tmp_path)
    assert data["summary"]["total"] == GOLDEN_TOTAL
    assert data["summary"]["by_severity"] == GOLDEN_BY_SEVERITY
    assert data["summary"]["by_rule"] == GOLDEN_BY_RULE
    for f in data["findings"]:
        assert (prod_workspace / f["file"]).exists(), f"missing source: {f['file']}"


def test_scan_writes_all_artifacts_named_rust_audit(prod_workspace, tmp_path):
    scan(prod_workspace, tmp_path, "--fail-on", "high")
    assert list(tmp_path.glob("rust-audit-*.md")), "Markdown report missing"
    assert list(tmp_path.glob("rust-audit-*.sarif")), "SARIF report missing"
    assert list(tmp_path.glob("not-executed-*.md")), "not-executed report missing"
    assert report(tmp_path)["tool"] == "Rust Audit"
    sarif = json.loads(sorted(tmp_path.glob("rust-audit-*.sarif"))[0].read_text())
    assert sarif["runs"][0]["tool"]["driver"]["name"] == "Rust Audit"


def test_exit_codes_match_documented_contract(prod_workspace, tmp_path):
    # R01 (unimplemented stub) is absent from this production tree: a clean
    # pass over real code must exit 0.
    p = scan(prod_workspace, tmp_path / "clean", "--rules", "R01", "--fail-on", "high")
    assert p.returncode == 0, p.stdout + p.stderr
    assert report(tmp_path / "clean")["summary"]["total"] == 0

    assert scan(tmp_path / "does-not-exist", tmp_path / "out-missing").returncode == 2
    empty = tmp_path / "empty"
    empty.mkdir()
    assert scan(empty, tmp_path / "out-empty").returncode == 2


def test_config_disables_exactly_the_named_rule(prod_workspace, tmp_path):
    cfg = tmp_path / "rust-audit.toml"
    cfg.write_text('[rules]\ndisabled = ["R02"]\n')
    scan(prod_workspace, tmp_path / "cfg", "--config", str(cfg), "--fail-on", "high")
    data = report(tmp_path / "cfg")
    expected = {k: v for k, v in GOLDEN_BY_RULE.items() if k != "R02"}
    assert data["summary"]["by_rule"] == expected
    assert data["summary"]["total"] == GOLDEN_TOTAL - GOLDEN_BY_RULE["R02"]


def test_fix_dry_run_changes_nothing(prod_workspace, tmp_path):
    ws = tmp_path / "dry"
    shutil.copytree(prod_workspace, ws, ignore=shutil.ignore_patterns(".git", "target", "report"))
    before = snapshot(ws)
    p = run("fix", str(ws), "--dry-run")
    assert p.returncode == 0, p.stdout + p.stderr
    assert snapshot(ws) == before, "fix --dry-run modified the workspace"


def test_fix_is_transactional_and_idempotent_on_production_code(prod_workspace, tmp_path):
    # Documented safe-fix policy: fmt + clippy --fix (MachineApplicable) MAY
    # rewrite sources; the contract is that fix deletes nothing, adds only the
    # generated policy file, passes validation without rollback and converges.
    ws = tmp_path / "applied"
    shutil.copytree(prod_workspace, ws, ignore=shutil.ignore_patterns(".git", "target", "report"))
    before = snapshot(ws)
    p1 = run("fix", str(ws))
    assert p1.returncode == 0, p1.stdout + p.stderr
    assert "REVERTED" not in p1.stdout, "validation failed and fix rolled back"
    after = snapshot(ws)
    missing = set(before) - set(after)
    added = set(after) - set(before)
    assert not missing, f"fix deleted production files: {sorted(missing)}"
    assert added == GENERATED, f"unexpected new files: {sorted(added ^ GENERATED)}"

    # Transactional contract: a second run must apply nothing (idempotent).
    p2 = run("fix", str(ws))
    assert p2.returncode == 0, p2.stdout + p2.stderr
    assert snapshot(ws) == after, "second fix run must apply nothing"
